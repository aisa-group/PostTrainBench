DEFAULT_JUDGE_MODEL_MAP = {
    # judge_lib.sh's JUDGE_DEFAULT_MODEL and general_judge/judge.conf's
    # JUDGE_MODEL are bare upstream names. The Kaggle model proxy serves
    # dated slugs, so they are remapped here.
    #
    # The targets must be RESPONSES-wired slugs, not merely valid ones. The
    # proxy picks its backend from the slug, not from the shape of the
    # request (harbor says so itself at
    # container/harbor-base/entrypoint-common.sh:509-518), and codex speaks
    # only the Responses API. A Responses call against a Chat-Completions-wired
    # slug crosses the FE/BE mismatch in b/544507744 and comes back
    # contaminated rather than as a clean 4xx. Confirmed by the model-proxy
    # team on 2026-09-01, and independently re-confirmed.
    #
    # Measured against the live catalog (GET $MODEL_PROXY_URL, 2026-09-01,
    # 145 models):
    #   openai/gpt-5.4-responses      ABSENT  <- marvin named it; it does not exist
    #   openai/gpt-5.5-responses      present
    #   openai/gpt-5.6-sol-responses  present
    #   openai/gpt-5.6-terra          present, and so is openai/gpt-5.6-terra-cc
    #
    # The `-cc` sibling is what makes the terra mapping safe: the bare 5.6
    # slug is the Responses one and `-cc` is the Chat-Completions variant, so
    # upstream's own `gpt-5.6-terra` needs no substitution.
    #
    # gpt-5.4 STAYS gpt-5.4: the project permits gpt-5.4 and gpt-5.6 only,
    # not gpt-5.5 (2026-09-01). Substituting gpt-5.5-responses was briefly
    # written here and reverted — it is a different model generation, which
    # the `-2026-03-05` mapping was not, and the measurement does not support
    # paying that cost: prod run 867385 ran codex against
    # `openai/gpt-5.4-2026-03-05` over the proxy's Responses endpoint and got
    # a clean `turn.completed` with the correct answer. The FE/BE mismatch in
    # b/544507744 did not appear on that turn.
    #
    # ⚠️ What that run does NOT prove: it was a one-shot "reply with PONG".
    # A judge turn is multi-turn and tool-heavy, which is where a contaminated
    # stream would actually bite. Treat gpt-5.4 as UNPROVEN for judge-shaped
    # work until a real judge completes on it.
    #
    # If it does turn out to be contaminated, the fidelity-preserving fix is
    # for the model-proxy team to add `openai/gpt-5.4-responses` (it does NOT
    # exist today — checked against the live 145-model catalog on 2026-09-01).
    # Substituting another generation is a last resort and needs sign-off.
    "gpt-5.4": "openai/gpt-5.4-2026-03-05",
    "gpt-5.6-terra": "openai/gpt-5.6-terra",
}


