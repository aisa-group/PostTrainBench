def generate_task(
    *,
    benchmark_id: str,
    model_to_train: str,
    agent: str,
    agent_config: str,
    num_hours: int,
    num_gpus: int,
    output_dir: Path,
    eval_script: str,
    judge_model_map: dict[str, str],
    agent_timeout_sec: float | None,
    verifier_timeout_sec: float,
    hf_cache_mounts: list[str],
    torch_backend: str,
    allow_missing_test_data: bool,
    skip_cuda_check: bool,
    docker_image: str | None,
    verifier_docker_image: str | None,
    verifier_base_image: str | None,
    agent_base_image: str | None,
    gpu_types: list[str],
    cpus: int,
    memory_mb: int,
    storage_mb: int,
    smoke: bool,
) -> Path:
    slug = cfg.task_slug(benchmark_id, model_to_train)
    task_dir = output_dir / slug
    if task_dir.exists():
        shutil.rmtree(task_dir)
    task_dir.mkdir(parents=True)

    benchmark_name = read_benchmark_name(benchmark_id)

    instruction = generate_instruction(
        benchmark_id, model_to_train, str(num_hours), PROMPT_AGENT, num_gpus
    )
    (task_dir / "instruction.md").write_text(instruction)

    stage_environment(task_dir, benchmark_id, eval_script, allow_missing_test_data,
                      torch_backend, docker_image, smoke, agent_base_image)

    metadata = {
        "benchmark_id": benchmark_id,
        "benchmark_name": benchmark_name,
        "model_to_train": model_to_train,
        "model_key": cfg.model_key(model_to_train),
        "agent": agent,
        "agent_config": agent_config,
        "num_hours": num_hours,
        "num_gpus": num_gpus,
        "eval_script": eval_script,
        # score_run.py's baseline fallback, from scripts/baselines.json.
        "zeroshot_baseline": cfg.zeroshot_baseline(benchmark_id, model_to_train),
        # scripts/factors.json — the weight this benchmark carries in the
        # overall metric (aggregate.py:compute_weighted_metric). Not used by
        # the verifier; recorded so the Kaggle parent mapping can be built
        # from the task rather than from a second copy of the table.
        "benchmark_weight": cfg.load_factors()[benchmark_id],
        "smoke_build": smoke,
        "skip_cuda_check": skip_cuda_check,
        "docker_image": docker_image,
        "verifier_docker_image": verifier_docker_image,
        "verifier_base_image": verifier_base_image,
        "gpu_types": gpu_types,
        "cpus": cpus,
        "memory_mb": memory_mb,
        "storage_mb": storage_mb,
    }

    stage_tests(
        task_dir, benchmark_id, model_to_train, agent, agent_config,
        judge_model_map, metadata, hf_cache_mounts, torch_backend,
        verifier_docker_image, verifier_base_image, smoke,
    )

    if agent_timeout_sec is None:
        agent_timeout_sec = float(
            (num_hours * 60 + cfg.AGENT_GRACE_MINUTES) * 60
        )

    (task_dir / "task.toml").write_text(
        render_task_toml(
            slug=slug,
            benchmark_id=benchmark_id,
            benchmark_name=benchmark_name,
            model_to_train=model_to_train,
            num_hours=num_hours,
            agent_timeout_sec=agent_timeout_sec,
            verifier_timeout_sec=verifier_timeout_sec,
            hf_cache_mounts=hf_cache_mounts,
            skip_cuda_check=skip_cuda_check,
            docker_image=docker_image,
            agent_base_image=agent_base_image,
            verifier_docker_image=verifier_docker_image,
            gpu_types=gpu_types,
            cpus=cpus,
            memory_mb=memory_mb,
            storage_mb=storage_mb,
            smoke=smoke,
        )
    )
    return task_dir


