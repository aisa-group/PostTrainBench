def stage_tests(
    task_dir: Path,
    benchmark_id: str,
    model_to_train: str,
    agent: str,
    agent_config: str,
    judge_model_map: dict[str, str],
    metadata: dict,
    hf_cache_mounts: list[str],
    torch_backend: str,
    verifier_docker_image: str | None,
    verifier_base_image: str | None,
    smoke: bool,
) -> None:
    tests_dir = task_dir / "tests"
    tests_dir.mkdir(parents=True, exist_ok=True)
    _compose_dotenv(tests_dir)        # D232

    # A base image means harbor BUILDS this task's verifier from the thin
    # Dockerfile, layering the task's own tests/ over prebuilt heavy layers.
    # That is the only way per-task /tests reaches a separate verifier env --
    # see the comment at the top of Dockerfile.perTask.
    if verifier_base_image and not smoke:
        src_name = "Dockerfile.perTask"
    else:
        src_name = "Dockerfile.smoke" if smoke else "Dockerfile"
    _copy(TEMPLATE_DIR / "tests" / src_name, tests_dir / "Dockerfile")
    # strip_web_search.py is the PTB_DISABLE_WEB_SEARCH=1 diagnostic shim; it
    # is inert unless that env var is set (see test.sh). Staged unconditionally
    # so a diagnostic run needs an env var, not a rebuild.
    for name in ("test.sh", "score_run.py", "strip_web_search.py"):
        _copy(TEMPLATE_DIR / "tests" / name, tests_dir / name)
    _copy(
        REPO_ROOT / "containers" / "requirements-direct.txt",
        tests_dir / "requirements-direct.txt",
    )

    # A partial checkout at the upstream paths. judge_lib.sh, test.sh and
    # get_judge_prompt.py all navigate relative to a repo root, and
    # evaluate.py is invoked with `--templates-dir ../../../../src/eval/
    # templates`; keeping the layout means none of them need patching.
    repo = tests_dir / "repo"

    _copy(
        REPO_ROOT / "src" / "eval" / "tasks" / benchmark_id,
        repo / "src" / "eval" / "tasks" / benchmark_id,
    )
    _copy(REPO_ROOT / "src" / "eval" / "templates", repo / "src" / "eval" / "templates")

    # run_task.sh:324 runs src/trace_parsing/parse_trace.py from the repo root.
    # The parsers import each other as flat siblings (parse_trace.py:20-25,
    # claude_parser.py:10), which works because python puts a script's own
    # directory on sys.path — so the whole package has to land at the upstream
    # path and be invoked the upstream way. __pycache__ is a build artefact of
    # the checkout, not part of the source.
    _copy(REPO_ROOT / "src" / "trace_parsing", repo / "src" / "trace_parsing")
    shutil.rmtree(repo / "src" / "trace_parsing" / "__pycache__", ignore_errors=True)

    # parse_trace.py:81 calls sanitize_trace.load_api_key_secrets(), which
    # hard-exits when there is no .env at sanitize_trace.py's
    # parents[2] (sanitize_trace.py:14-15, :33-34) — i.e. at the repo root.
    # Upstream's repo root always has one. example.env is that file's shipped
    # template and carries the `*_API_KEY` names; load_api_key_secrets prefers
    # the live environment value over the file's `your-*` placeholder
    # (sanitize_trace.py:47), so staging the template reproduces upstream's
    # redaction exactly without baking a secret into the image.
    _copy(REPO_ROOT / "example.env", repo / ".env")

    judges_src = REPO_ROOT / "src" / "judges"
    judges_dst = repo / "src" / "judges"
    _copy(judges_src / "get_judge_prompt.py", judges_dst / "get_judge_prompt.py")
    _copy(judges_src / "judge_tools", judges_dst / "judge_tools")
    for judge in cfg.ALL_JUDGES:
        _copy(judges_src / judge / "judge.conf", judges_dst / judge / "judge.conf")
        _copy(judges_src / judge / "prompt.md", judges_dst / judge / "prompt.md")

    _copy(
        REPO_ROOT / "containers" / "delete_hf_models.py",
        repo / "containers" / "delete_hf_models.py",
    )
    _copy(
        REPO_ROOT / "containers" / "other_home_data" / ".codex",
        repo / "containers" / "other_home_data" / ".codex",
    )

    # This compose file is the ONLY way to get the HF cache into the SEPARATE
    # verifier container.
    #
    # Harbor appends `--mounts` (how a Kaggle dataset mount arrives) to the
    # agent environment only — trial/trial.py:1299 is `base +
    # list(self.config.environment.mounts or [])`, while the verifier env is
    # built from trial/trial.py:681-692, a single fixed bind of /logs/verifier.
    # task.toml cannot help: EnvironmentConfig has no `mounts` field
    # (models/task/config.py:421) and, because pydantic `extra` is left at
    # "ignore", writing one is silently dropped rather than rejected.
    # `extra_docker_compose` is blanked for the verifier at trial/trial.py:648.
    # Upstream needs no equivalent — it binds the same overlay into the
    # evaluation phase directly (run_task.sh:410-411).
    #
    # The path is written literally rather than interpolated: `${VAR}` would
    # resolve against the verifier's env, where PTB_HF_CACHE_MOUNT need not be
    # set, and an empty expansion produces a malformed bind. If the source
    # does not exist docker creates an empty directory, so a run without the
    # cache dataset degrades to the previous behaviour instead of failing.
    _compose_override(
        tests_dir / "docker-compose.yaml",
        "" if verifier_docker_image else torch_backend,
        [f"{m}:{m}:ro" for m in hf_cache_mounts],
        {"PTB_VERIFIER_BASE": verifier_base_image} if verifier_base_image and not smoke else None,
    )

    (tests_dir / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    (tests_dir / "judge_model_map.json").write_text(
        json.dumps(judge_model_map, indent=2) + "\n"
    )


