def _compose_dotenv(project_dir: Path) -> None:
    """Ship an empty `.env` wherever docker compose will look for one.

    D232. `docker compose` stats `.env` in its --project-directory on EVERY
    invocation, and harbor points that at the task's directory on the gcsfuse
    mount (environments/docker/docker.py:620). Nothing of ours references the
    file; compose looks for it unconditionally.

    With no file present that is a NEGATIVE lookup, and the Kaggle mount runs
    gcsfuse with --implicit-dirs. gcsfuse cannot answer ENOENT straight from
    the 404: it must issue an `objects.list` with prefix `.env/` to rule out an
    implicit directory. If that list call hits a blip -- 503, timeout -- the
    layer returns **EIO instead of ENOENT**. Compose ignores ENOENT and treats
    EIO as fatal, exits 1, and the command dies under `set -euo pipefail`
    before it has run. That is how a claude-code install died on a path it
    never mentions (run 1120769; verified against GCS artifacts and gcsfuse
    mount.go:147 by the Benchmarks team).

    A 0-byte file turns the negative lookup into a positive one: GCS answers
    200, gcsfuse caches the metadata locally, and no objects.list is ever
    issued for it again. Compose parses an empty .env to zero variables, so
    there is no behavioural change.

    Not a fix for the underlying fault -- fleet-wide this costs 0.15-5.84% of
    all Harbor runs -- but it removes the condition that triggers it for ours.
    """
    (project_dir / ".env").write_text("")


def stage_environment(
    task_dir: Path, benchmark_id: str, eval_script: str,
    allow_missing_test_data: bool, torch_backend: str,
    docker_image: str | None, smoke: bool,
    agent_base_image: str | None = None,
) -> None:
    env_dir = task_dir / "environment"
    env_dir.mkdir(parents=True, exist_ok=True)
    _compose_dotenv(env_dir)          # D232

    # A smoke build swaps in a lightweight base with the same layout; see
    # template/environment/Dockerfile.smoke for what it does and does not
    # cover.
    # agent_base_image => build a thin per-task layer on that base, so this
    # task's own home/ actually reaches /home/ben. A prebuilt `docker_image`
    # makes harbor pull and never build, which is how every agent ended up
    # with gsm8k's evaluate.py -- see the comment at the top of
    # environment/Dockerfile.perTask.
    if agent_base_image and not smoke:
        src_dockerfile = "Dockerfile.perTask"
    else:
        src_dockerfile = "Dockerfile.smoke" if smoke else "Dockerfile"
    _copy(TEMPLATE_DIR / "environment" / src_dockerfile, env_dir / "Dockerfile")
    _copy(TEMPLATE_DIR / "environment" / "preflight.sh", env_dir / "preflight.sh")
    # Delivers ARG TORCH_BACKEND, which nothing else on the Kaggle path can,
    # and PTB_AGENT_BASE for the per-task build.
    _compose_override(env_dir / "docker-compose.yaml",
                      "" if (docker_image and not agent_base_image) else torch_backend, [],
                      {"PTB_AGENT_BASE": agent_base_image}
                      if agent_base_image and not smoke else None)
    _copy(
        REPO_ROOT / "containers" / "requirements-direct.txt",
        env_dir / "requirements-direct.txt",
    )

    home = env_dir / "home"
    task = home / "task"
    task.mkdir(parents=True, exist_ok=True)

    tasks_dir = REPO_ROOT / "src" / "eval" / "tasks" / benchmark_id

    # run_task.sh:63 — the chosen eval script always lands as evaluate.py.
    _copy(_require(tasks_dir / eval_script, "the agent's eval entry point"),
          task / "evaluate.py")

    # run_task.sh:64-66
    if (tasks_dir / "evaluation_code").is_dir():
        _copy(tasks_dir / "evaluation_code", task / "evaluation_code")

    # run_task.sh:67
    _copy(REPO_ROOT / "src" / "eval" / "templates", task / "templates")

    # run_task.sh:69-71 — task_context contents are flattened into task/.
    task_context = tasks_dir / "task_context"
    if task_context.is_dir():
        for item in task_context.iterdir():
            _copy(item, task / item.name)

    # run_task.sh:72
    _copy(REPO_ROOT / "containers" / "other_home_data" / ".codex", home / ".codex")

    # run_task.sh:124-128 — the scripts the agent phase runs in the sandbox.
    # create_timer.sh is added to this set: upstream runs it on the host
    # during job prep, and preflight.sh runs it in-container instead (see
    # its header).
    for name in (
        "check_cuda.py",
        "check_cuda_writing.py",
        "system_monitor.sh",
        "timestamp_lines.py",
        "update_agent_cli.sh",
        "create_timer.sh",
    ):
        _copy(REPO_ROOT / "src" / "utils" / name, home / name)

    # run_task.sh:136-141 — the agent's self-decontamination tooling.
    # Upstream hard-errors when test_data.json is absent, because its
    # presence also decides whether get_prompt.py emits the "Decontamination
    # Tool" section. A build without it produces a different prompt, so the
    # override has to be explicit.
    test_data = tasks_dir / "test_data.json"
    if not test_data.exists():
        if not allow_missing_test_data:
            raise FileNotFoundError(
                f"src/eval/tasks/{benchmark_id}/test_data.json not found — "
                f"required for the agent's decontamination tooling "
                f"(run_task.sh:136). Fetch it with "
                f"src/judges/test_data_download/download_test_data.sh, or pass "
                f"--allow-missing-test-data to build a task whose prompt omits "
                f"the Decontamination Tool section."
            )
        print(
            f"  WARNING: no test_data.json for {benchmark_id}; the generated "
            f"prompt omits the Decontamination Tool section and the "
            f"contamination judge has no reference set."
        )
    else:
        _copy(test_data, home / "test_data.json")
    _copy(
        REPO_ROOT / "src" / "judges" / "judge_tools" / "contamination_check.py",
        home / "contamination_check.py",
    )


