def _copy(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if src.is_dir():
        shutil.copytree(src, dst, dirs_exist_ok=True)
    else:
        shutil.copy2(src, dst)


def _compose_override(dest: Path, torch_backend: str, binds: list[str],
                      extra_args: dict[str, str] | None = None) -> None:
    """Write a `docker-compose.yaml` beside a Dockerfile, for what task.toml can't say.

    Harbor layers `<environment_dir>/docker-compose.yaml` over its own generated
    stack when the file exists (`environments/docker/docker.py:363-364`,
    `_environment_docker_compose_path`), and it does so for the agent
    environment and the separate verifier environment alike. That makes this
    the only seam for two things task.toml cannot express:

    * **build args.** Harbor's build file is
      `build: {context: ${CONTEXT_DIR}}` with no `args:`
      (`environments/docker/docker-compose-build.yaml`), and nothing in the
      Kaggle path passes `--build-arg`. Both Dockerfiles declare
      `ARG TORCH_BACKEND=auto` and use it on the `uv pip install vllm` line,
      so without this the ARG default is the only reachable value.
    * **bind mounts into the verifier**, which `--mounts` never reaches
      (see stage_tests).

    The service name must be `main` — that is what harbor's own files declare.
    """
    lines = ["# Generated by build_tasks.py. Harbor layers this over its own",
             "# compose stack; see _compose_override() for why it must exist.",
             "services:",
             "  main:"]
    args = dict(extra_args or {})
    if torch_backend:
        args["TORCH_BACKEND"] = torch_backend
    if args:
        # Only meaningful when harbor actually builds. With a prebuilt
        # docker_image there is no build step, so emitting build.args would be
        # misleading noise — but the volumes below are still required, because
        # this file remains the only way a mount reaches the verifier.
        #
        # PTB_VERIFIER_BASE rides the same channel and for the same reason:
        # harbor's build file declares no `args:`, so a build ARG has no other
        # route into the image.
        lines += ["    build:", "      args:"]
        lines += [f"        {k}: {v}" for k, v in sorted(args.items())]
    if binds:
        lines.append("    volumes:")
        lines.extend(f"      - {b}" for b in binds)
    if len(lines) <= 4:
        # Nothing to say: no build args (prebuilt image) and no binds. A
        # `services: main:` with an empty body is not valid compose, and
        # harbor layers this file blindly if it exists, so write nothing.
        dest.unlink(missing_ok=True)
        return
    dest.write_text("\n".join(lines) + "\n")


def _require(path: Path, why: str) -> Path:
    if not path.exists():
        raise FileNotFoundError(f"{path} not found — {why}")
    return path


def read_benchmark_name(benchmark_id: str) -> str:
    """get_prompt.py:17 — the human-readable name, from benchmark.txt."""
    return (
        REPO_ROOT / "src" / "eval" / "tasks" / benchmark_id / "benchmark.txt"
    ).read_text(encoding="utf-8").strip()


def read_required_api_keys(benchmark_id: str) -> list[str]:
    """get_prompt.py:24 — provider keys this benchmark's own grading needs.

    run_task.sh:96-121 provisions the agent sandbox with exactly
    `agents/<agent>/api_keys.json` ∪ this list. The agent half of that
    allowlist has no analogue here (harbor injects model credentials
    unconditionally), but the benchmark half is reproduced: only the
    benchmarks that declare a key get it in [environment.env].
    """
    info = json.loads(
        (REPO_ROOT / "src" / "eval" / "tasks" / benchmark_id / "info.json")
        .read_text(encoding="utf-8")
    )
    return info.get("required_api_keys", [])


def generate_instruction(
    benchmark_id: str, model_to_train: str, num_hours: str, agent: str, num_gpus: int
) -> str:
    """Run get_prompt.py exactly as run_task.sh:75 does.

    A subprocess rather than an import: get_prompt.py resolves
    `src/eval/tasks/...` relative to the working directory, so it has to run
    from the repo root, and shelling out guarantees the output is whatever
    upstream would have produced — including the trailing claude clause and
    the `{setup_other}` / `{decontamination_tool}` / `{eval_api_note}`
    branches.
    """
    result = subprocess.run(
        [
            sys.executable,
            "src/eval/general/get_prompt.py",
            "--model-to-train", model_to_train,
            "--benchmark-id", benchmark_id,
            "--num-hours", num_hours,
            "--num-gpus", str(num_gpus),
            "--agent", agent,
        ],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise RuntimeError(
            f"get_prompt.py failed for {benchmark_id}/{model_to_train}:\n"
            f"{result.stderr}"
        )
    # run_task.sh:76 captures stdout through `$( )`, which strips trailing
    # newlines, then writes it back with `echo`. Net effect: exactly one
    # trailing newline.
    return result.stdout.rstrip("\n") + "\n"


