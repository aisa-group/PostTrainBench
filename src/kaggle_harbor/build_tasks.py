#!/usr/bin/env python3
"""Generate Harbor tasks for the PostTrainBench sweep.

One task per (benchmark, model) cell — 28 in the full sweep, the same matrix
`src/commit_utils/commit.sh` submits to HTCondor.

Design rule, applied everywhere: **do not reimplement anything the repo
already does.** The agent prompt comes from `src/eval/general/get_prompt.py`,
run as a subprocess with the same arguments `run_task.sh:75` passes. The
judge prompts come from `src/judges/get_judge_prompt.py`, invoked by the
verifier at run time. `timer.sh` comes from `src/utils/create_timer.sh`,
invoked in the container at start time. Every file the sandbox needs is
copied out of the checkout rather than transcribed. The only new code is the
Harbor plumbing that has no upstream counterpart: task.toml, the two
Dockerfiles, preflight.sh, test.sh and score_run.py.

The staging layout mirrors upstream paths exactly, so relative paths inside
copied scripts keep resolving:

    environment/home/  ->  the JOB_DIR run_task.sh:55-155 assembles
    tests/repo/        ->  the subtree the judge and evaluation phases read

Usage:

    python src/kaggle_harbor/build_tasks.py --all --agent codex --output ./tasks
    python src/kaggle_harbor/build_tasks.py --benchmark gsm8k \\
        --model Qwen/Qwen3-1.7B-Base --agent claude --output ./tasks
"""

