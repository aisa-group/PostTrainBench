def render_task_toml(
    *,
    slug: str,
    benchmark_id: str,
    benchmark_name: str,
    model_to_train: str,
    num_hours: int,
    agent_timeout_sec: float,
    verifier_timeout_sec: float,
    hf_cache_mounts: list[str],
    skip_cuda_check: bool,
    docker_image: str | None,
    agent_base_image: str | None,
    verifier_docker_image: str | None,
    gpu_types: list[str],
    cpus: int,
    memory_mb: int,
    storage_mb: int,
    smoke: bool,
) -> str:
    required_keys = read_required_api_keys(benchmark_id)

    def resources(indent_header: str, image: str | None = None) -> str:
        # environments/definition.py:26-36 — a non-empty docker_image makes
        # harbor PULL instead of build, unless force_build is set (we never
        # set it), and the Dockerfile's presence is then irrelevant. Upstream
        # builds its .sif once into POST_TRAIN_BENCH_CONTAINERS_DIR and every
        # job reuses it (run_task.sh:249), so pulling a prebuilt image is
        # CLOSER to upstream than rebuilding per run, not further from it.
        # INSIDE the section, not above it. Emitting this before the header
        # put it in whatever section preceded — [metadata] — where harbor
        # never looks, so docker_image read as None and it rebuilt from the
        # Dockerfile anyway. That silently wasted a full 38-minute run.
        img = f'\ndocker_image = "{image}"' if image else ""
        return f"""[{indent_header}]{img}
network_mode = "public"
build_timeout_sec = 3600.0
os = "linux"
cpus = {cpus}
memory_mb = {memory_mb}
storage_mb = {storage_mb}
gpus = {cfg.REQUEST_GPUS}
gpu_types = {json.dumps(gpu_types)}
mcp_servers = []
"""

    agent_env = {
        # set_env_vars.sh:24 / .codex/config.toml
        "HF_HOME": cfg.SANDBOX_HF_HOME,
        # run_task.sh:236-237
        "VLLM_API_KEY": cfg.VLLM_API_KEY,
        "PYTHONNOUSERSITE": "1",
        # agents/claude/solve.sh:5 -- `export BASH_MAX_TIMEOUT_MS="36000000"`,
        # i.e. exactly the 10 h agent budget.
        #
        # This is the ceiling on how long ONE Bash tool call may block before
        # Claude Code kills the command and hands control back to the model.
        # It is NOT the session timeout: the session cap ends the whole run,
        # this ends a single command. Left at the CLI default (minutes), a
        # multi-hour `python train.py` gets killed mid-training and the model's
        # only recourse is to background the job and poll -- which is precisely
        # how a run ends with training still in flight, no final_model/, and
        # collect.py substituting the zero-shot baseline.
        #
        # The original pairs this with the non-interactive clause: the timeout
        # removes the need to background anything, the clause is the backstop.
        # We shipped the backstop without the fix until 2026-09-03.
        #
        # Set for every harness, not just Claude. It is a Claude Code variable
        # and the others ignore it, so gating it would add a branch with no
        # observable effect.
        "BASH_MAX_TIMEOUT_MS": "36000000",
        # D229. The exeunit exposes EVERY GPU on the node -- /dev/nvidia0 to
        # /dev/nvidia7 -- even though the task declares gpus = 1. check_cuda.py
        # fails its first branch (`device_count != NUM_GPUS`, 8 != 1), touches
        # cuda_not_available and exits 1; preflight.sh is the healthcheck, so
        # Harbor retries three times and aborts the trial with
        # HealthcheckError. That killed 8/8 runs of the 2026-09-04 sanity
        # sweep at t=86 s, across all three harnesses.
        #
        # Pinning to device 0 makes torch.cuda.device_count() == 1, so
        # check_cuda.py passes COMPLETELY UNMODIFIED -- the deviation is this
        # one variable, not a patch to the original's gate.
        #
        # "0" is not "physical GPU 0". The NVIDIA container runtime renumbers
        # per container, so index 0 always means "the first GPU this container
        # was given". That keeps the value correct if the platform later packs
        # one task per GPU: the task's assigned device is its index 0, and no
        # re-push is needed.
        #
        # ⚠️ Relaxing check_cuda.py instead (>= 1, or deleting it) is NOT
        # equivalent and is actively unsafe: the check is an assertion, not a
        # mechanism. All 8 devices would stay visible and HF Trainer defaults
        # to DataParallel across every visible GPU, silently training on 8 and
        # producing a score that cannot be compared with the leaderboard.
        "CUDA_VISIBLE_DEVICES": "0",
        "NUM_GPUS": str(cfg.REQUEST_GPUS),
        # read by preflight.sh when it invokes create_timer.sh
        "PTB_NUM_HOURS": str(num_hours),
        # read by preflight.sh, which links the read-only cache mount back
        # under HF_HOME one repo at a time. Upstream needs no equivalent: its
        # cache arrives as a fuse-overlayfs bound straight onto HF_HOME.
        "PTB_HF_CACHE_MOUNT": ":".join(hf_cache_mounts),
    }
    # run_task.sh:83-85 + the info.json half of the allowlist: OPENAI_API_KEY
    # reaches the agent only on the benchmarks whose grading needs it.
    for key in required_keys:
        agent_env[key] = "${" + key + "}"
    # DIVERGENCE, and forced. Upstream hands the agent a real OpenAI key, so
    # arenahardwriting/healthbench grading reaches api.openai.com with no base
    # URL. Kaggle's key is a *model-proxy* key (entrypoint-common.sh:313-314),
    # and both benchmarks' evaluate.py grade through a bare `openai.OpenAI()`,
    # which reads OPENAI_BASE_URL from the environment. Without this the two
    # LLM-judged benchmarks dial the public endpoint and 401 — inside the
    # agent's own loop, where it looks like a task failure rather than a
    # misconfiguration. Same root cause as divergence 2 (codex needing
    # `-c openai_base_url=`); [verifier.env] already carries the pair.
    if "OPENAI_API_KEY" in required_keys:
        agent_env["OPENAI_BASE_URL"] = "${OPENAI_BASE_URL:-}"
        agent_env["PTB_JUDGE_MODEL"] = "openai/gpt-5-mini"
    # check_cuda.py:44 is `if "H100" in name`, so the gate fails on any other
    # device — and it runs as the healthcheck, which aborts the trial before
    # the agent starts (environments/base.py:1376-1380). Kaggle's only
    # accelerator pool is a single L4, so a real-image test run there needs
    # this off. Decoupled from --smoke on purpose: --smoke also swaps in
    # lightweight Dockerfiles, which is the opposite of what a "does the real
