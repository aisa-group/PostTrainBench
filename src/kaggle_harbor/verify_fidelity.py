def verify_task(task_dir: Path) -> None:
    meta = json.loads((task_dir / "tests" / "metadata.json").read_text())
    benchmark_id = meta["benchmark_id"]
    model_to_train = meta["model_to_train"]
    tasks_src = REPO_ROOT / "src" / "eval" / "tasks" / benchmark_id
    home = task_dir / "environment" / "home"
    repo = task_dir / "tests" / "repo"

    def same(staged: Path, source: Path, what: str) -> None:
        check(staged.exists(), f"{task_dir.name}: missing {what} ({staged})")
        if staged.exists():
            check(filecmp.cmp(staged, source, shallow=False),
                  f"{task_dir.name}: {what} differs from {source.relative_to(REPO_ROOT)}")

    def same_tree(staged: Path, source: Path, what: str,
                  skip_dir: str | None = None) -> None:
        check(staged.is_dir(), f"{task_dir.name}: missing dir {what}")
        if not staged.is_dir():
            return
        for src_file in sorted(source.rglob("*")):
            if not src_file.is_file():
                continue
            if skip_dir and skip_dir in src_file.relative_to(source).parts:
                continue
            same(staged / src_file.relative_to(source), src_file,
                 f"{what}/{src_file.relative_to(source)}")

    # --- B1. agent sandbox home == run_task.sh:55-155 -----------------------
    same(home / "task" / "evaluate.py", tasks_src / meta["eval_script"],
         "task/evaluate.py")
    same_tree(home / "task" / "templates", REPO_ROOT / "src" / "eval" / "templates",
              "task/templates")
    if (tasks_src / "evaluation_code").is_dir():
        same_tree(home / "task" / "evaluation_code", tasks_src / "evaluation_code",
                  "task/evaluation_code")
    if (tasks_src / "task_context").is_dir():
        for item in sorted((tasks_src / "task_context").iterdir()):
            if item.is_file():
                same(home / "task" / item.name, item, f"task/{item.name}")
    same_tree(home / ".codex", REPO_ROOT / "containers" / "other_home_data" / ".codex",
              ".codex")
    for name in ("check_cuda.py", "check_cuda_writing.py", "system_monitor.sh",
                 "timestamp_lines.py", "update_agent_cli.sh", "create_timer.sh"):
        same(home / name, REPO_ROOT / "src" / "utils" / name, name)
    same(home / "contamination_check.py",
         REPO_ROOT / "src" / "judges" / "judge_tools" / "contamination_check.py",
         "contamination_check.py")
    if (tasks_src / "test_data.json").exists():
        same(home / "test_data.json", tasks_src / "test_data.json", "test_data.json")

    # timer.sh must NOT be staged: preflight.sh generates it at container
    # start so CREATION_DATE is stamped near agent start, as upstream does.
    check(not (home / "task" / "timer.sh").exists(),
          f"{task_dir.name}: timer.sh was baked into the image; its CREATION_DATE "
          f"would be image build time, not agent start")

    # --- B2. verifier repo subtree ------------------------------------------
    same_tree(repo / "src" / "eval" / "tasks" / benchmark_id, tasks_src,
              f"repo/src/eval/tasks/{benchmark_id}")
    same_tree(repo / "src" / "eval" / "templates",
              REPO_ROOT / "src" / "eval" / "templates", "repo/src/eval/templates")
    same(repo / "src" / "judges" / "get_judge_prompt.py",
         REPO_ROOT / "src" / "judges" / "get_judge_prompt.py", "get_judge_prompt.py")
    same_tree(repo / "src" / "judges" / "judge_tools",
              REPO_ROOT / "src" / "judges" / "judge_tools", "judge_tools")
    for judge in cfg.ALL_JUDGES:
        for f in ("judge.conf", "prompt.md"):
            same(repo / "src" / "judges" / judge / f,
                 REPO_ROOT / "src" / "judges" / judge / f, f"{judge}/{f}")
    same(repo / "containers" / "delete_hf_models.py",
         REPO_ROOT / "containers" / "delete_hf_models.py", "delete_hf_models.py")
    # run_task.sh:324's parser package, at the upstream path so its flat
    # sibling imports resolve. __pycache__ is a build artefact of the
    # checkout, deliberately not staged.
    same_tree(repo / "src" / "trace_parsing",
              REPO_ROOT / "src" / "trace_parsing", "repo/src/trace_parsing",
              skip_dir="__pycache__")
    check(not (repo / "src" / "trace_parsing" / "__pycache__").exists(),
          f"{task_dir.name}: __pycache__ was staged into repo/src/trace_parsing")
    # sanitize_trace.py:33-34 hard-exits without a .env at the repo root.
    same(repo / ".env", REPO_ROOT / "example.env", "repo/.env")
    for d in (task_dir / "environment", task_dir / "tests"):
        same(d / "requirements-direct.txt",
             REPO_ROOT / "containers" / "requirements-direct.txt",
             f"{d.name}/requirements-direct.txt")

    # The relative path evaluate.py is invoked with, unchanged from
    # run_task.sh:421, has to resolve inside the staged tree.
    eval_cwd = repo / "src" / "eval" / "tasks" / benchmark_id
    resolved = (eval_cwd / "../../../../src/eval/templates").resolve()
    check(resolved == (repo / "src" / "eval" / "templates").resolve(),
          f"{task_dir.name}: --templates-dir ../../../../src/eval/templates "
          f"resolves to {resolved}, not the staged templates dir")

    # get_judge_prompt.py computes REPO_ROOT as its own parent.parent and
    # reads src/eval/tasks/<id>/info.json from there.
    check((repo / "src" / "eval" / "tasks" / benchmark_id / "info.json").exists(),
          f"{task_dir.name}: get_judge_prompt.py would not find info.json")

    # --- C. the prompt ------------------------------------------------------
    regenerated = build_tasks.generate_instruction(
        benchmark_id, model_to_train, str(meta["num_hours"]),
        build_tasks.PROMPT_AGENT, meta["num_gpus"],
    )
    actual = (task_dir / "instruction.md").read_text()
    check(actual == regenerated,
          f"{task_dir.name}: instruction.md differs from get_prompt.py output")

    # C2. The whole 1:1 claim, in one line, for every harness the task can be
    # run with: what the wrapper hands the real adapter must equal what
    # upstream's own pipeline produces for that agent name. Covers the split
    # between PROMPT_AGENT (what get_prompt.py saw) and metadata's real name.
    # Exhaustive over the wrappers that exist, derived from the module rather
    # than listed here so a new one cannot be added without being checked.
    # cursor_cli is absent because it has no wrapper (README divergence 15).
    wrapped = sorted(
        cls.PTB_AGENT_NAME
        for name, cls in vars(ptb_harness).items()
        if name.startswith("PtbHarness_")
    )
    check_eq(wrapped, ["claude", "codex", "gemini", "opencode"],
             "agents/ptb_harness.py wrapper roll-call")
    for upstream_agent in (meta["agent"], *wrapped):
        expected = build_tasks.generate_instruction(
            benchmark_id, model_to_train, str(meta["num_hours"]),
            upstream_agent, meta["num_gpus"],
        )
        check(ptb_harness.apply_agent_clause(actual, upstream_agent) == expected,
              f"{task_dir.name}: the wrapper's instruction for upstream agent "
              f"{upstream_agent!r} differs from get_prompt.py --agent "
              f"{upstream_agent}")

    # --- task.toml through harbor's own model -------------------------------
    from harbor.models.task.task import Task
    t = Task(task_dir)
    c = t.config
    check_eq(c.environment.workdir, cfg.SANDBOX_WORKDIR, f"{task_dir.name} workdir")
    check_eq(c.environment.cpus, cfg.REQUEST_CPUS, f"{task_dir.name} cpus")
    check_eq(c.environment.memory_mb, cfg.REQUEST_MEMORY_MB, f"{task_dir.name} memory_mb")
    check_eq(c.environment.storage_mb, cfg.REQUEST_DISK_MB, f"{task_dir.name} storage_mb")
    check_eq(c.environment.gpus, cfg.REQUEST_GPUS, f"{task_dir.name} gpus")
    check_eq(c.environment.gpu_types, cfg.GPU_TYPES, f"{task_dir.name} gpu_types")
    check(c.verifier.environment_mode.value == "separate",
          f"{task_dir.name}: verifier is not in separate mode")
    check(c.verifier.environment is not None and c.verifier.environment.gpus == 1,
          f"{task_dir.name}: verifier environment has no GPU (it runs vLLM)")
    sources = [a.source for a in c.artifacts]
    check(sources == [cfg.SANDBOX_HOME, cfg.AGENT_LOGS_DIR],
          f"{task_dir.name}: artifacts are {sources}, not the agent home plus "
          f"harbor's agent log dir (the raw trace test.sh turns into "
          f"solve_out.txt)")
    # An `exclude` on any artifact silently switches harbor from an uncapped
    # `docker compose cp` to a `tar czf` under a hardcoded 120 s timeout
    # (artifact_handler.py:335-347). final_model is ~8 GB of incompressible
    # weights and does not fit in 120 s, and the failure only shows up after
    # the agent's full budget is spent. Keep every artifact exclude-free.
    excluded = [(a.source, a.exclude) for a in c.artifacts if a.exclude]
    check(not excluded,
          f"{task_dir.name}: artifact exclude(s) {excluded} force harbor's "
          f"120s-capped tar path; the HF cache is linked in from "
          f"{cfg.HF_CACHE_MOUNT} instead so nothing needs excluding")
    # Every cache shard must sit outside the sandbox home for that to hold.
    # PTB_HF_CACHE_MOUNT is a colon-separated list: the cache ships as several
    # datasets to stay under the 1,000-file cap, and preflight.sh merges them.
    mounts = [m for m in c.environment.env.get("PTB_HF_CACHE_MOUNT", "").split(":") if m]
    check(bool(mounts), f"{task_dir.name}: PTB_HF_CACHE_MOUNT is unset")
    inside = [m for m in mounts if m.startswith(cfg.SANDBOX_HOME)]
    check(not inside,
          f"{task_dir.name}: cache shard(s) {inside} are inside "
          f"{cfg.SANDBOX_HOME}; the home artifact would copy the whole "
          f"HuggingFace cache")
    # tests/docker-compose.yaml is the only route a mount can take into a
    # separate verifier environment (trial/trial.py:681-692 vs :1299). Without
    # it the evaluation has no HF cache and gpqamain's gated dataset fails.
    # Every shard needs its own bind — a missing one is a silently partial
    # cache, which surfaces as a mystery download failure hours in.
    compose = (task_dir / "tests" / "docker-compose.yaml")
    body = compose.read_text() if compose.is_file() else ""
    unbound = [m for m in mounts if f"{m}:{m}:ro" not in body]
    check(not unbound,
          f"{task_dir.name}: tests/docker-compose.yaml does not bind {unbound} "
          f"into the verifier; the evaluation would run with a partial or "
          f"absent HF cache")
    check(c.environment.healthcheck is not None,
          f"{task_dir.name}: no healthcheck, so the CUDA gate and timer never run")

    # metadata's derived numbers
    check_eq(meta["zeroshot_baseline"],
             cfg.zeroshot_baseline(benchmark_id, model_to_train),
             f"{task_dir.name} zeroshot_baseline")
    check_eq(meta["benchmark_weight"], cfg.load_factors()[benchmark_id],
             f"{task_dir.name} benchmark_weight")

    # env the agent gets: only benchmarks that declare a key in info.json
    # should see it (run_task.sh's allowlist, benchmark half).
    required = build_tasks.read_required_api_keys(benchmark_id)
    for key in ("OPENAI_API_KEY", "OPENROUTER_API_KEY", "ANTHROPIC_API_KEY"):
        if key in required:
            check(key in c.environment.env,
                  f"{task_dir.name}: {key} is in info.json required_api_keys "
                  f"but not in [environment.env]")
        else:
            check(key not in c.environment.env,
                  f"{task_dir.name}: {key} is in [environment.env] but "
                  f"info.json does not require it — upstream withholds it")


# ---------------------------------------------------------------------------
# D. upstream line citations
# ---------------------------------------------------------------------------
#
# The port's comments carry ~180 `file:line` citations into upstream. They are
# the whole basis for reviewing it, and they rot silently: upstream inserts a
# line and every citation below it now points one line off. This caught real
# drift on 2026-09-01 — `judge_lib.sh:37` was cited for `ALL_JUDGES` after
# upstream moved it to :31, and six of score_run.py's `utils.py:` citations
# pointed into function bodies rather than at the `def` they named.
#
# Two checks: the line must exist, and where the citation is next to a name we
# can recognise, that name must appear at the cited line.

CITATION_RE = re.compile(r"\b(run_task\.sh|judge_lib\.sh|collect\.py|utils\.py):(\d+)")

CITED_SOURCES = {
    "run_task.sh": Path("src/run_task.sh"),
    "judge_lib.sh": Path("src/judges/judge_lib.sh"),
    "collect.py": Path("scripts/collect.py"),
    "utils.py": Path("scripts/utils.py"),
}

# (upstream file, line, token that must appear within +/-1 line of it).
# Only anchors worth pinning: the ones a reader navigates by.
CITATION_ANCHORS = [
    ("judge_lib.sh", 31, "ALL_JUDGES"),
    ("judge_lib.sh", 35, "JUDGE_DEFAULT_MODEL"),
    ("judge_lib.sh", 37, "JUDGE_CONTAINER"),
    ("judge_lib.sh", 167, "codex"),
    ("judge_lib.sh", 186, "parse_trace"),
    ("run_task.sh", 246, "--home"),
    ("run_task.sh", 419, "vllm_debug"),
    ("collect.py", 183, "baseline_data"),
    ("utils.py", 379, "def load_metrics"),
    ("utils.py", 410, "def judgement_path"),
    ("utils.py", 432, "def load_judgement"),
    ("utils.py", 468, "def optional_judgement_path"),
    ("utils.py", 517, "def load_api_judgement"),
    ("utils.py", 556, "def missing_required_judgements"),
    ("utils.py", 581, "def judgement_to_cell"),
    ("utils.py", 627, "def load_time_taken"),
]


def verify_citations() -> None:
    print("\nD. upstream line citations")
    src = {}
    for name, rel in CITED_SOURCES.items():
        path = REPO_ROOT / rel
        check(path.exists(), f"cited upstream file missing: {rel}")
        src[name] = path.read_text().split("\n") if path.exists() else []

    here = Path(__file__).resolve().parent
    scanned = [here / "template" / "tests" / "test.sh",
               here / "template" / "tests" / "score_run.py",
               here / "template" / "tests" / "Dockerfile",
               here / "template" / "environment" / "preflight.sh",
               here / "template" / "environment" / "Dockerfile",
               here / "DEVIATIONS.md"]

    n = 0
    for f in scanned:
        if not f.exists():
            continue
        for m in CITATION_RE.finditer(f.read_text()):
            name, line = m.group(1), int(m.group(2))
            n += 1
            check(1 <= line <= len(src[name]),
                  f"{f.name}: cites {name}:{line} but that file has "
                  f"{len(src[name])} lines")
    print(f"   {n} citations in range across {len(scanned)} files")

    for name, line, token in CITATION_ANCHORS:
        window = "\n".join(src[name][max(0, line - 2):line + 1])
        check(token.lower() in window.lower(),
              f"citation anchor drifted: {name}:{line} should be at/near "
              f"{token!r}, but that line reads "
              f"{src[name][line - 1].strip()[:70]!r}")
    print(f"   {len(CITATION_ANCHORS)} anchors still point at the right code")


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--tasks", type=Path, required=True)
    # An APPROVED deviation is still a failure -- it must keep printing, keep
    # being counted, and keep appearing in the report. What --waive changes is
    # only whether it blocks the push.
    #
    # Without this the gate is all-or-nothing, so the single approved
    # deviation we ship with (D224, storage_mb 81920 vs 409600) makes it
    # impossible to ever push, and the only way out is to bypass the gate
    # entirely -- which would also bypass the 4820 checks that matter.
    #
    # Waiving is per-substring and deliberately narrow: a failure counts as
    # waived only if its text contains one of these. Any failure of any other
    # kind still exits non-zero.
    p.add_argument("--waive", action="append", default=[], metavar="SUBSTRING",
                   help="do not block the push on failures containing this "
                        "(they are still reported). Repeatable.")
    p.add_argument("--expect-waived", type=int, default=None, metavar="N",
                   help="require exactly N waived failures. Guards against a "
                        "waiver silently covering more than it was meant to.")
    args = p.parse_args()

    verify_constants()
    verify_agent_wrapper(args.tasks)
    verify_citations()

    task_dirs = sorted(d for d in args.tasks.iterdir() if (d / "task.toml").exists())
    print(f"\nB+C. {len(task_dirs)} generated task(s)")
    for d in task_dirs:
        before = len(failures)
        verify_task(d)
        status = "ok" if len(failures) == before else f"{len(failures) - before} FAILED"
        print(f"   {d.name:<48} {status}")

    waived = [f for f in failures
              if any(w in str(f) for w in args.waive)]
    blocking = [f for f in failures if f not in waived]

    print(f"\n{checks} checks, {len(failures)} failures "
          f"({len(waived)} waived, {len(blocking)} blocking)")
    for f in blocking:
        print(f"\n  FAIL: {f}")
    for f in waived:
        print(f"\n  WAIVED: {f}")

    if args.expect_waived is not None and len(waived) != args.expect_waived:
        print(f"\n  WAIVER MISMATCH: expected exactly {args.expect_waived} "
              f"waived failure(s), got {len(waived)}. The waiver is covering a "
              f"different set than it was written for -- refusing to pass.")
        return 1
    return 1 if blocking else 0


if __name__ == "__main__":
    sys.exit(main())
