def verify_agent_wrapper(tasks_root: Path) -> None:
    """agents/ptb_harness.py against the two upstream dispatchers it feeds.

    The `--agent` string is read by get_prompt.py:120 ('claude' substring) and
    by parse_trace.py:36-44 (substring match against five parser keys, hard
    error on more than one, silent raw copy on none). The slug the platform
    passes through as KAGGLE_AGENT_HARNESS is one string for both, so both are
    asserted here.
    """
    print("\nA2. custom-import harness wrappers")

    # The clause literal, against get_prompt.py's own source.
    text = (REPO_ROOT / "src" / "eval" / "general" / "get_prompt.py").read_text(
        encoding="utf-8"
    )
    marker = '        result += """'
    start = text.index(marker) + len(marker)
    check_eq(ptb_harness._NON_INTERACTIVE_CLAUSE, text[start:text.index('"""', start)],
             "ptb_harness._NON_INTERACTIVE_CLAUSE vs get_prompt.py:121-123")

    wrappers = [
        ("PtbHarness_claude", "claude", "claude"),
        ("PtbHarness_codex", "codex", "codex"),
        ("PtbHarness_gemini", "gemini", "gemini"),
        ("PtbHarness_opencode", "opencode", "opencode"),
    ]
    for class_name, upstream_agent, parser_key in wrappers:
        cls = getattr(ptb_harness, class_name, None)
        check(cls is not None, f"agents/ptb_harness.py has no {class_name}")
        if cls is None:
            continue
        check_eq(cls.PTB_AGENT_NAME, upstream_agent, f"{class_name}.PTB_AGENT_NAME")

        slug = f"agents.ptb_harness:{class_name}"
        matches = [key for key in parse_trace.PARSERS if key in slug]
        check_eq(matches, [parser_key], f"parse_trace keys matched by {slug}")
        check_eq("claude" in slug, "claude" in upstream_agent,
                 f"get_prompt.py:120's rule on {slug} vs upstream name")

        # harbor/utils/import_path.py:29 — the machinery `--agent` uses.
        from harbor.agents.base import BaseAgent
        from harbor.utils.import_path import import_class
        try:
            check(import_class(slug, base=BaseAgent, label="agent") is cls,
                  f"{slug} does not resolve to {class_name}")
        except Exception as exc:  # noqa: BLE001
            check(False, f"{slug} failed to import: {exc}")

    # The staged copy the executor actually imports.
    staged = tasks_root / "agents"
    for name in ("__init__.py", "ptb_harness.py"):
        src = Path(__file__).resolve().parent / "agents" / name
        dst = staged / name
        check(dst.exists(), f"agents/{name} not staged at {staged}")
        if dst.exists():
            check(filecmp.cmp(dst, src, shallow=False),
                  f"staged agents/{name} differs from src/kaggle_harbor/agents/{name}")
    check(not (staged / "__pycache__").exists(),
          f"{staged}/__pycache__ was staged")

    # --- the CLI version each harness runs ---------------------------------
    # Upstream floats every agent CLI to @latest: each agents/<a>/solve.sh
    # opens with `update_agent_cli.sh <cli>`, which npm-installs `<pkg>@latest`
    # ahead of the baked copy, and the opt-out is commented out in example.env.
    # So the port must float too. Left unpinned, harbor SKIPS the install when
    # any build is already present, which would freeze all four at the
    # standard.def fallback — that is what made a gpt-5.6-sol run die on
    # `unknown variant 'max'`. Re-derived from upstream so a regression here
    # fails rather than silently pinning.
    for agent_dir in ("claude", "codex", "gemini", "opencode"):
        solve = REPO_ROOT / "agents" / agent_dir / "solve.sh"
        if solve.exists():
            check("update_agent_cli.sh" in solve.read_text(),
                  f"upstream agents/{agent_dir}/solve.sh no longer auto-updates "
                  f"its CLI — PTB_DEFAULT_VERSION='latest' may no longer be right")
    example_env = (REPO_ROOT / "example.env").read_text()
    check(not re.search(r"^\s*POST_TRAIN_BENCH_SKIP_CLI_UPDATE\s*=",
                        example_env, re.MULTILINE),
          "upstream example.env now SETS POST_TRAIN_BENCH_SKIP_CLI_UPDATE, so "
          "upstream pins its CLIs and PTB_DEFAULT_VERSION='latest' is wrong")
    # DELIBERATE DEVIATION, 2026-09-03, at the user's instruction: each harness
    # is pinned to the version Kaggle has REGISTERED for it, rather than
    # floating to @latest the way upstream's update_agent_cli.sh does.
    #
    # The two checks above still run, because they guard the reasoning behind
    # the original choice: if upstream ever stops auto-updating, the tradeoff
    # being made here changes and someone should notice.
    #
    # What is asserted now is that NOTHING is pinned. The agent slug names its
    # build and the platform passes it through as `--ak version=`, which the
    # sweep's own logs confirm ("version pin '0.146.1' (--ak version=)"). A pin
    # in the port would be a second copy of that fact, maintained by hand and
    # read by nothing -- and the starter template does not keep one either
    # (opencode_binary_agent.py:91 is `@{version} if version else @latest`).
    #
    # A slug naming a build that does not exist is the platform's error to
    # report, not ours to pre-empt.
    for class_name, _upstream_agent, _parser_key in wrappers:
        cls = getattr(ptb_harness, class_name, None)
        if cls is None:
            continue
        check(cls.PTB_DEFAULT_VERSION == "latest",
              f"{class_name}.PTB_DEFAULT_VERSION is "
              f"{cls.PTB_DEFAULT_VERSION!r}; the port pins no CLI builds -- the "
              f"scheduled slug supplies the version")

    print(f"   {len(wrappers)} wrappers: clause literal, parser dispatch, "
          f"import path, staged copy, CLI pinned to the registered harness "
          f"version")


