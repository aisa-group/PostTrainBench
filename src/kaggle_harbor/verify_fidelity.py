#!/usr/bin/env python3
"""Check that the generated tasks still match upstream.

"1:1 with the original" is only worth something if it is testable, so this
asserts it rather than documenting it. Three kinds of check:

  A. Constants — every value transcribed into config.py is re-derived from
     the upstream file it came from (commit.sh, run_task.sh, single_task.sub,
     judge_lib.sh) and compared. Catches upstream drifting away from the
     port.

  B. Copied files — every file staged into a task is byte-compared with its
     source in the checkout. Catches accidental edits to a copy.

  C. Generated prompts — instruction.md is regenerated by running
     get_prompt.py and diffed. Catches any divergence in the one artifact
     the agent actually reads.

Plus task.toml parsing through harbor's own model, so a schema mistake is
caught here and not on the platform.

    python src/kaggle_harbor/verify_fidelity.py --tasks ./tasks
"""

from __future__ import annotations

import argparse
import filecmp
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import config as cfg  # noqa: E402
import build_tasks  # noqa: E402

REPO_ROOT = cfg.REPO_ROOT

# parse_trace.py:20-25 imports its parsers as flat siblings, which works for a
# script because python puts its directory on sys.path. Importing it as a
# module needs the same entry.
sys.path.insert(0, str(REPO_ROOT / "src" / "trace_parsing"))

import parse_trace  # noqa: E402
from agents import ptb_harness  # noqa: E402

failures: list[str] = []
checks = 0


def check(condition: bool, message: str) -> None:
    global checks
    checks += 1
    if not condition:
        failures.append(message)


def check_eq(actual, expected, what: str) -> None:
    check(actual == expected, f"{what}\n     upstream: {expected!r}\n     port:     {actual!r}")


# ---------------------------------------------------------------------------
# A. constants
# ---------------------------------------------------------------------------

def verify_constants() -> None:
    print("A. constants re-derived from upstream")

    # --- the matrix, from commit.sh -----------------------------------------
    commit = (REPO_ROOT / "src" / "commit_utils" / "commit.sh").read_text()

    def bash_array(name: str) -> list[str]:
        m = re.search(rf"^{name}=\(\s*(.*?)\s*\)\s*$", commit, re.M | re.S)
        if not m:
            raise AssertionError(f"no {name}=( ... ) array in commit.sh")
        body = "\n".join(
            line.split("#", 1)[0] for line in m.group(1).splitlines()
        )
        return re.findall(r'"([^"]+)"', body)

    check_eq(cfg.MODELS, bash_array("models"), "commit.sh models[]")
    check_eq(cfg.BENCHMARKS, bash_array("evals"), "commit.sh evals[]")
    print(f"   models   {len(cfg.MODELS)}  evals {len(cfg.BENCHMARKS)}"
          f"  -> {len(cfg.MODELS) * len(cfg.BENCHMARKS)} cells")

    # --- resources, from every submit file ----------------------------------
    sub_dir = REPO_ROOT / "src" / "commit_utils"
    subs = sorted(sub_dir.rglob("*.sub"))
    check(len(subs) > 0, "no .sub files found under src/commit_utils")
    for sub in subs:
        text = sub.read_text()
        rel = sub.relative_to(REPO_ROOT)

        def val(key: str) -> str | None:
            m = re.search(rf"^\s*{key}\s*=\s*(\S+)", text, re.M)
            return m.group(1) if m else None

        # The baselines/ submit files describe zero-shot baseline jobs, which
        # scripts/utils.py excludes from the sweep (SKIP_METHODS) and which
        # are out of scope for this port.
        if "baselines" in str(rel):
            continue
        if val("request_cpus"):
            check_eq(int(val("request_cpus")), cfg.REQUEST_CPUS, f"{rel} request_cpus")
        if val("request_memory"):
            check_eq(int(val("request_memory")), cfg.REQUEST_MEMORY_MB, f"{rel} request_memory")
        # request_gpus is `$(num_gpus)`, a submit-file macro defaulted at the
        # top of the file and overridable per job with `-a num_gpus=`.
        # Compare against the default.
        gpus_raw = val("request_gpus")
        if gpus_raw:
            if gpus_raw.startswith("$("):
                macro = re.search(
                    rf"^\s*{re.escape(gpus_raw[2:-1])}\s*=\s*(\d+)", text, re.M
                )
                check(macro is not None, f"{rel} request_gpus macro {gpus_raw} has no default")
                if macro:
                    check_eq(int(macro.group(1)), cfg.REQUEST_GPUS, f"{rel} request_gpus default")
            else:
                check_eq(int(gpus_raw), cfg.REQUEST_GPUS, f"{rel} request_gpus")
        if val("request_disk"):
            disk = val("request_disk").upper().rstrip("G")
            check_eq(int(disk) * 1024, cfg.REQUEST_DISK_MB, f"{rel} request_disk")
        if "CUDADeviceName" in text:
            check("H100" in text, f"{rel} no longer pins an H100")
    print(f"   {len(subs)} submit file(s) agree on cpus/memory/disk/gpus/H100")

    # --- eval retry schedule, from run_task.sh ------------------------------
    run_task = (REPO_ROOT / "src" / "run_task.sh").read_text()

    retries = [
        int(m) for m in re.findall(r"^run_evaluation_with_retry (\d+)", run_task, re.M)
    ]
    check_eq(tuple(retries), cfg.EVAL_PHASE_RETRIES, "run_task.sh retry schedule")

    timeout = re.search(r"--kill-after=60s (\d+)s", run_task)
    check_eq(int(timeout.group(1)), cfg.EVAL_ATTEMPT_TIMEOUT_SEC,
             "run_task.sh per-attempt eval timeout")

    # The two `case "${EVALUATION_TASK}"` blocks that set MAX_TOKENS_ARG, in
    # source order: phase 2 then phase 3.
    blocks = re.findall(
        r'case "\$\{EVALUATION_TASK\}" in\n(.*?)\nesac', run_task, re.S
    )
    check(len(blocks) == 2, f"expected 2 MAX_TOKENS case blocks, found {len(blocks)}")
    if len(blocks) == 2:
        for block, expected, label in zip(
            blocks, (cfg.MAX_TOKENS_PHASE2, cfg.MAX_TOKENS_PHASE3), ("phase2", "phase3")
        ):
            parsed = dict(
                re.findall(r"(\w+)\)\s*\n\s*MAX_TOKENS_ARG=\"([^\"]*)\"", block)
            )
            parsed.pop("*", None)
            check_eq(parsed, expected, f"run_task.sh MAX_TOKENS {label}")
    print("   run_task.sh retry counts, attempt timeout and both token tables match")

    # --- grace period -------------------------------------------------------
    grace = re.search(r'"\$\(\(NUM_HOURS \* 60 \+ (\d+)\)\)m"', run_task)
    check_eq(int(grace.group(1)), cfg.AGENT_GRACE_MINUTES, "run_task.sh agent grace minutes")

    # --- sandbox layout -----------------------------------------------------
    check(f'--home "${{JOB_DIR}}:{cfg.SANDBOX_HOME}"' in run_task,
          f"run_task.sh no longer mounts the home at {cfg.SANDBOX_HOME}")
    check(f'--pwd "{cfg.SANDBOX_WORKDIR}"' in run_task,
          f"run_task.sh no longer uses {cfg.SANDBOX_WORKDIR} as the working dir")

    set_env = (REPO_ROOT / "src" / "commit_utils" / "set_env_vars.sh").read_text()
    m = re.search(r'export HF_HOME_NEW="([^"]+)"', set_env)
    check_eq(m.group(1), cfg.SANDBOX_HF_HOME, "set_env_vars.sh HF_HOME_NEW")
    print("   sandbox home, working dir and HF_HOME match")

    # --- judges, from judge_lib.sh ------------------------------------------
    judge_lib = (REPO_ROOT / "src" / "judges" / "judge_lib.sh").read_text()
    m = re.search(r"^ALL_JUDGES=\(([^)]*)\)", judge_lib, re.M)
    check_eq(m.group(1).split(), cfg.ALL_JUDGES, "judge_lib.sh ALL_JUDGES")
    m = re.search(r'JUDGE_DEFAULT_MODEL="([^"]+)"', judge_lib)
    check_eq(m.group(1), cfg.JUDGE_DEFAULT_MODEL, "judge_lib.sh JUDGE_DEFAULT_MODEL")
    m = re.search(r'JUDGE_DEFAULT_REASONING_EFFORT="([^"]+)"', judge_lib)
    check_eq(m.group(1), cfg.JUDGE_DEFAULT_REASONING_EFFORT,
             "judge_lib.sh JUDGE_DEFAULT_REASONING_EFFORT")
    print(f"   {len(cfg.ALL_JUDGES)} judges, default model and effort match")

    # --- container pins, from the .def files --------------------------------
    standard = (REPO_ROOT / "containers" / "standard.def").read_text()
    check(f"vllm=={cfg.VLLM_VERSION}" in standard, "standard.def vllm pin")
    check(f"flash-attn=={cfg.FLASH_ATTN_VERSION}" in standard, "standard.def flash-attn pin")
    check(cfg.INSPECT_EVALS_COMMIT in standard, "standard.def inspect_evals commit")
    check(f"@openai/codex@{cfg.AGENT_CODEX_VERSION}" in standard, "standard.def codex pin")
    check(cfg.BASE_IMAGE in standard, "standard.def base image")

    gpt55 = (REPO_ROOT / "containers" / "gpt_5_5.def").read_text()
    check(f"@openai/codex@{cfg.VERIFIER_CODEX_VERSION}" in gpt55, "gpt_5_5.def codex pin")

    general_conf = (REPO_ROOT / "src" / "judges" / "general_judge" / "judge.conf").read_text()
    check(f'JUDGE_CODEX_VERSION="{cfg.GENERAL_JUDGE_CODEX_VERSION}"' in general_conf,
          "general_judge JUDGE_CODEX_VERSION")
    print("   container package pins match standard.def / gpt_5_5.def")

    # --- the two Dockerfiles are transcriptions of the .def files -----------
    # Not a byte diff (different formats); check that every pinned version in
    # the .def also appears in the Dockerfile that ports it.
    tmpl = build_tasks.TEMPLATE_DIR
    agent_df = (tmpl / "environment" / "Dockerfile").read_text()
    verif_df = (tmpl / "tests" / "Dockerfile").read_text()
    for token in (cfg.BASE_IMAGE, f"vllm=={cfg.VLLM_VERSION}",
                  f"flash-attn=={cfg.FLASH_ATTN_VERSION}", cfg.INSPECT_EVALS_COMMIT):
        check(token in agent_df, f"environment/Dockerfile missing {token}")
        check(token in verif_df, f"tests/Dockerfile missing {token}")
    check(f"@openai/codex@{cfg.AGENT_CODEX_VERSION}" in agent_df,
          "environment/Dockerfile codex pin drifted from standard.def")
    # D227: the verifier's codex is DELIBERATELY 0.146.1, not gpt_5_5.def's
    # 0.124.0. 0.124.0 has no HTTPS fallback, so the model proxy's 307 on the
    # websocket upgrade is fatal to it and test.sh had to inject a whole custom
    # model_providers block to work around it. 0.146.1 is the version Kaggle
    # registers as its canonical codex harness and falls back cleanly, so the
    # judges run stock configuration. One deviation traded for a smaller one.
    check("@openai/codex@0.146.1" in verif_df,
          "tests/Dockerfile codex pin is not 0.146.1 (D227)")

    # Every npm pin in gpt_5_5.def, not just codex. The verifier image is the
    # union of gpt_5_5.def and vllm_debug.def (D90), and the merge takes
    # gpt_5_5's pins (D91). An earlier revision installed codex alone because
    # it is the only CLI the verifier invokes; that was an efficiency argument
    # and it is not a reason to diverge, so all four ship (D92). Re-derived
    # from upstream here so dropping one again fails the check.
    gpt55 = (REPO_ROOT / "containers" / "gpt_5_5.def").read_text()
    npm_pins = re.findall(r"(@?[\w./@-]+@[\d.]+)\s*\\?\s*$", gpt55, re.MULTILINE)
    npm_pins = [p for p in npm_pins if "/" in p or p.startswith("opencode")]
    check(len(npm_pins) == 4,
          f"expected 4 npm pins in gpt_5_5.def, parsed {len(npm_pins)}: {npm_pins}")
    for pin in npm_pins:
        # codex is exempt: D227 pins it forward to 0.146.1. Every OTHER pin
        # must still match gpt_5_5.def exactly, so dropping one still fails.
        if pin.startswith("@openai/codex@"):
            check(pin == "@openai/codex@0.124.0",
                  f"gpt_5_5.def's codex pin moved to {pin}; D227 assumed 0.124.0 "
                  f"and its reasoning (no HTTPS fallback) should be rechecked")
            continue
        check(pin in verif_df,
              f"tests/Dockerfile is missing gpt_5_5.def's npm pin {pin} — "
              f"the union must install all four CLIs, not only the one it uses")
    vllm_debug = (REPO_ROOT / "containers" / "vllm_debug.def").read_text()
    check("inspect_ai_vllm_stdout" in vllm_debug and "inspect_ai_vllm_stdout" in verif_df,
          "tests/Dockerfile missing inspect_ai_vllm_stdout from vllm_debug.def")

    # --- scoring tables -----------------------------------------------------
    factors = cfg.load_factors()
    check_eq(sorted(factors), sorted(cfg.BENCHMARKS), "factors.json covers the benchmarks")
    total = sum(factors.values())
    check(abs(total - 1.0) < 1e-6,
          f"factors.json weights sum to {total}, not 1.0 — the root aggregation "
          f"is a weighted average and assumes they do")
    baselines = cfg.load_baselines()["zeroshot"]
    for model in cfg.MODELS:
        key = cfg.model_key(model)
        check(key in baselines, f"baselines.json has no zeroshot entry for {key}")
        for bench in cfg.BENCHMARKS:
            check(bench in baselines.get(key, {}),
                  f"baselines.json zeroshot[{key}] missing {bench}")
    print(f"   factors.json sums to {total:.6f}; baselines cover all 28 cells")


